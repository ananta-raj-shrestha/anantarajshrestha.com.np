let currentLang = localStorage.getItem('site-lang') === 'np' ? 'np' : 'en';
let typedHome, typedAbout;

function applyTranslations(lang){
    document.querySelectorAll('.i18n-text').forEach(function(el){
        const text = el.getAttribute(lang === 'np' ? 'data-np' : 'data-en');
        if (text !== null) el.textContent = text;
    });
    document.querySelectorAll('.i18n-placeholder').forEach(function(el){
        const text = el.getAttribute(lang === 'np' ? 'data-np-placeholder' : 'data-en-placeholder');
        if (text !== null) el.setAttribute('placeholder', text);
    });
    const aboutParaEl = document.getElementById('about-para');
    if (aboutParaEl) aboutParaEl.innerText = translations[lang].aboutPara;

    $('#lang-switch .lang-option').each(function(){
        $(this).toggleClass('active', $(this).data('lang') === lang);
    });

    document.documentElement.lang = lang === 'np' ? 'ne' : 'en';
}

function initTyped(lang){
    if (typedHome) typedHome.destroy();
    if (typedAbout) typedAbout.destroy();
    typedHome = new Typed(".typing", {
        strings: translations[lang].typing,
        typeSpeed: 100,
        backSpeed: 60,
        loop: true
    });
    typedAbout = new Typed(".typing-2", {
        strings: translations[lang].typing2,
        typeSpeed: 100,
        backSpeed: 60,
        loop: true
    });
}

$(document).ready(function(){
    // set up the page in the saved (or default) language before anything else runs
    applyTranslations(currentLang);
    initTyped(currentLang);

    $('#lang-switch').on('click', function(){
        currentLang = currentLang === 'en' ? 'np' : 'en';
        localStorage.setItem('site-lang', currentLang);
        applyTranslations(currentLang);
        initTyped(currentLang);
    });
    // keyboard support since #lang-switch is a div acting as a button
    $('#lang-switch').on('keydown', function(e){
        if (e.key === 'Enter' || e.key === ' '){
            e.preventDefault();
            $(this).trigger('click');
        }
    });

    $(window).scroll(function(){
        // sticky navbar on scroll script
        if(this.scrollY > 20){
            $('.navbar').addClass("sticky");
        }else{
            $('.navbar').removeClass("sticky");
        }
        
        // scroll-up button show/hide script
        if(this.scrollY > 500){
            $('.scroll-up-btn').addClass("show");
        }else{
            $('.scroll-up-btn').removeClass("show");
        }
    });

    // slide-up script
    $('.scroll-up-btn').click(function(){
        $('html').animate({scrollTop: 0});
        // removing smooth scroll on slide-up button click
        $('html').css("scrollBehavior", "auto");
    });

    $('.navbar .menu li a').click(function(){
        // applying again smooth scroll on menu items click
        $('html').css("scrollBehavior", "smooth");
        // close the mobile menu after a link is tapped
        $('.navbar .menu').removeClass("active");
        $('#menu-toggle-btn i').removeClass("active");
    });

    // toggle menu/navbar script
    // FIX: previously bound to ".menu-btn", a class shared with every
    // nav link (<a class="menu-btn">Home</a> etc.) and the dropdown's
    // caret icon. That collision meant tapping a link also re-fired the
    // hamburger toggle, and the icon-toggle selector grabbed unrelated
    // icons. Scoping this to the button's own id (#menu-toggle-btn)
    // fixes the mobile tap behavior.
    $('#menu-toggle-btn').click(function(){
        $('.navbar .menu').toggleClass("active");
        $(this).find('i').toggleClass("active");
    });

    // owl carousel script
    $('.carousel').owlCarousel({
        margin: 20,
        loop: true,
        autoplay: true,
        autoplayTimeOut: 6000,
        autoplayHoverPause: true,
        responsive: {
            0:{
                items: 1,
                nav: false
            },
            2000:{
                items: 2,
                nav: false
            },
            4000:{
                items: 3,
                nav: false
            }
        }
    });
});

document.onkeydown = (e) => {
    if (e.key == 123) {
        e.preventDefault();
    }
    if (e.ctrlKey && e.shiftKey && e.key == 'I') {
        e.preventDefault();
    }
    if (e.ctrlKey && e.shiftKey && e.key == 'C') {
        e.preventDefault();
    }
    if (e.ctrlKey && e.shiftKey && e.key == 'J') {
        e.preventDefault();
    }
    if (e.ctrlKey && e.key == 'U') {
        e.preventDefault();
    }
};
// Ripple Effects
document.onclick = (e) => applyCursorRippleEffect(e);

function applyCursorRippleEffect(e) {
   const ripple = document.createElement("div");
  
   ripple.className = "ripple";
   document.body.appendChild(ripple);

  ripple.style.left = `${e.clientX}px`;
  ripple.style.top = `${e.clientY}px`; 
   ripple.style.animation = `ripple-effect .4s  linear`;
   ripple.onanimationend = () => {
     document.body.removeChild(ripple);
     
   }
  
}
